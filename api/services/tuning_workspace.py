"""
Tuning Workspace Service.

Provides a first-class data model for organizing work on a specific vehicle:

    Vehicle          -- the bike (identity that survives across jobs)
      TuningSession  -- one tuning job on that bike
        Iteration    -- one flash cycle within the session (iter_0 = baseline)

On-disk layout:

    vehicles/
      <vehicle_id>/
        profile.json
        sessions/
          <session_id>/
            session.json
            base_tune/               (immutable archive of flashed base PVV)
              base.pvv
            iterations/
              iter_0/
                iteration.json
                pulls/               (WP8, TXT, PV-CSV captured under this flash)
                patches/             (PVV patches generated by DynoAI)
                analyses/            (NextGen / AutoTune payloads)
              iter_1/ ...

Disk is the source of truth. JSON sidecar files make each entity self-describing.
This replaces the hand-routed OneDrive folder workflow used on the Racile job.
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import threading
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

__all__ = [
    "Vehicle",
    "TuningSession",
    "Iteration",
    "SessionStatus",
    "TuningWorkspace",
    "WorkspaceError",
    "get_workspace",
]

# =============================================================================
# Errors
# =============================================================================


class WorkspaceError(Exception):
    """Raised on workspace invariant violations."""


# =============================================================================
# Dataclasses
# =============================================================================


@dataclass
class Vehicle:
    """A tuned vehicle. Identity survives across all sessions for this bike."""

    id: str
    name: str
    year: Optional[int] = None
    make: str = ""
    model: str = ""
    displacement_ci: Optional[float] = None
    ecu_signature: Optional[str] = None
    watch_folder: Optional[str] = None
    notes: str = ""
    created_at: str = field(default_factory=lambda: _utc_now())
    updated_at: str = field(default_factory=lambda: _utc_now())

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class TuningSession:
    """One tuning job on a specific vehicle. Has a base tune + N iterations."""

    id: str
    vehicle_id: str
    base_tune_sha256: Optional[str] = None
    status: str = "active"
    notes: str = ""
    created_at: str = field(default_factory=lambda: _utc_now())
    updated_at: str = field(default_factory=lambda: _utc_now())
    active_iteration_id: Optional[str] = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class Iteration:
    """One flash cycle. iter_0 is the baseline (no patch applied yet)."""

    id: str
    session_id: str
    index: int
    patch_filename: Optional[str] = None
    flashed_at: Optional[str] = None
    notes: str = ""
    created_at: str = field(default_factory=lambda: _utc_now())

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class SessionStatus:
    """Computed readiness checklist for a session's active iteration."""

    session_id: str
    iteration_id: Optional[str]
    has_vehicle: bool
    has_base_tune: bool
    pull_count: int
    has_afr_data: bool
    ready_to_analyze: bool
    checklist: list[dict[str, Any]]

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


# =============================================================================
# Helpers
# =============================================================================

_SLUG_RE = re.compile(r"[^a-z0-9_-]+")


def _utc_now() -> str:
    """UTC ISO-8601 with Z suffix, millisecond precision."""
    return (
        datetime.now(timezone.utc)
        .isoformat(timespec="milliseconds")
        .replace("+00:00", "Z")
    )


def slugify(value: str) -> str:
    """Lowercase kebab-ish slug safe for filesystem use."""
    v = value.strip().lower()
    v = v.replace(" ", "_")
    v = _SLUG_RE.sub("", v)
    v = v.strip("-_")
    return v or "untitled"


def _atomic_write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )
    tmp.replace(path)


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256_file(path: Path, bufsize: int = 65536) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while chunk := f.read(bufsize):
            h.update(chunk)
    return h.hexdigest()


